#!/usr/bin/env python3
"""Generate the static C/udev control map from buttons.json; --check detects drift."""
import argparse,json,html
from pathlib import Path
root=Path(__file__).resolve().parent
buttons=json.loads((root/'buttons.json').read_text())
assert len(buttons)==19 and len({b['number'] for b in buttons})==19
assert len({b['linux_code'] for b in buttons})==19
assert all(b['linux_code']+8<=255 for b in buttons)
assert all((root/'icons'/f"{b['icon']}.svg").is_file() for b in buttons)
header='''/* Generated by input/generate.py from input/buttons.json. Semantic IDs are stable.
 * Physical AT scans are model-specific; application input uses standard X11/Qt.
 */
#ifndef READER_KEYS_H
#define READER_KEYS_H
enum reader_button { READER_NONE = 0,
'''+''.join(f"    READER_{b['id']} = {b['number']},\n" for b in buttons)+'''};
struct reader_key { unsigned scan, key; enum reader_button id; const char *name; const char *icon; };
static const struct reader_key reader_keys[] = {
'''+''.join(f'    {{0x{b["scan"]},{b["linux_code"]},READER_{b["id"]},"{b["id"].replace("_"," ")}","{b["icon"]}"}},\n' for b in buttons)+'''};
#define READER_KEY_COUNT (sizeof(reader_keys)/sizeof(reader_keys[0]))
static inline enum reader_button reader_button_from_key(unsigned key) {
    unsigned n;
    for(n=0;n<READER_KEY_COUNT;++n) if(reader_keys[n].key==key)return reader_keys[n].id;
    if(key==96)return READER_OK; /* USB keypad Enter */
    if(key==158)return READER_BACK; /* dedicated keyboard Back */
    if(key==138)return READER_GUIDE; /* dedicated Help */
    if(key==57)return READER_PLAY; /* Space on a keyboard */
    return READER_NONE;
}
static inline const char *reader_button_icon_name(enum reader_button id) {
    unsigned n;
    for(n=0;n<READER_KEY_COUNT;++n) if(reader_keys[n].id==id)return reader_keys[n].icon;
    return "";
}
#endif
'''
hwdb='# Generated by input/generate.py. Attached USB keyboards are unaffected.\nevdev:atkbd:dmi:*:svnIntelCorporation:pnColbert:*\n'+''.join(f' KEYBOARD_KEY_{b["scan"]}={b["linux_name"]}\n' for b in buttons)
doc=(root/'README.md').read_text().split('<!-- generated table -->')[0]+'<!-- generated table -->\n\n'
doc+='| Button | Location / symbol | Linux code | XKB symbol | Icon name | Default role |\n| --- | --- | --- | --- | --- | --- |\n'
for b in buttons:
    doc+=f'| `{b["id"]}` | {b["location"]}; {b["symbol"]} | `{b["linux_name"].upper()}` ({b["linux_code"]}) | `{b["xkb"]}` | `{b["icon"]}` | {b["action"]} |\n'
doc+='\n![Physical button symbols](button-reference.svg)\n'
sheet=['<svg xmlns="http://www.w3.org/2000/svg" width="960" height="760" viewBox="0 0 960 760"><rect width="960" height="760" fill="black"/>']
for i,b in enumerate(buttons):
    left=(i%4)*240+16;top=(i//4)*150+12
    icon=(root/'icons'/f'{b["icon"]}.svg').read_text()
    inner=icon[icon.index('>')+1:icon.rindex('</svg>')]
    sheet.append(f'<g transform="translate({left+85} {top+10}) scale(1.4)">{inner}</g><text x="{left+106}" y="{top+80}" text-anchor="middle" fill="white" font-family="sans-serif" font-size="17">{b["id"].replace("_"," ")}</text><text x="{left+106}" y="{top+106}" text-anchor="middle" fill="white" font-family="sans-serif" font-size="13">{html.escape(b["location"])}</text>')
sheet='\n'.join(sheet+['</svg>'])+'\n'
parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
for path,text in [(root.parent/'reader-keys.h',header),(root/'70-reread-keyboard.hwdb',hwdb),(root/'README.md',doc),(root/'button-reference.svg',sheet)]:
 if args.check:
  assert path.read_text()==text,f'{path} is stale; run antix/input/generate.py'
 else:path.write_text(text)
